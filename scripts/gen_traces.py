#!/usr/bin/env python3
"""Generate the allocation traces in traces/.

Each workload stresses the fit policies differently. A fixed seed per trace
keeps the files reproducible: re-running this script produces identical
output.

    python3 scripts/gen_traces.py [output_dir]
"""
import random
import sys
from pathlib import Path


def random_mix(rng, ops=20000, slots=400):
    """Uniform random sizes, random alloc/free order: the baseline."""
    live, out, next_id = [], [], 0
    for _ in range(ops):
        if live and (len(live) >= slots or rng.random() < 0.45):
            out.append(f"f {live.pop(rng.randrange(len(live)))}")
        else:
            out.append(f"a {next_id} {rng.randint(8, 4096)}")
            live.append(next_id)
            next_id += 1
    out += [f"f {i}" for i in live]
    return out


def small_large_interleave(rng, rounds=60):
    """Allocate small and large blocks alternately, free all the large ones,
    then ask for medium blocks. The holes left behind are big, but the
    small survivors pin them apart: a classic fragmentation pattern."""
    out, next_id = [], 0
    for _ in range(rounds):
        small, large = [], []
        for _ in range(40):
            out.append(f"a {next_id} {rng.randint(16, 64)}")
            small.append(next_id); next_id += 1
            out.append(f"a {next_id} {rng.randint(2048, 6144)}")
            large.append(next_id); next_id += 1
        for i in large:
            out.append(f"f {i}")
        medium = []
        for _ in range(60):
            out.append(f"a {next_id} {rng.randint(600, 3000)}")
            medium.append(next_id); next_id += 1
        for i in small + medium:
            out.append(f"f {i}")
    return out


def phases(rng, phases=40):
    """Program phases: build up many objects of a phase-specific size,
    keep a few long-lived survivors, free the rest."""
    out, next_id, survivors = [], 0, []
    for _ in range(phases):
        base = rng.choice([24, 80, 256, 1024, 3000])
        batch = []
        for _ in range(150):
            out.append(f"a {next_id} {max(1, int(rng.gauss(base, base / 5)))}")
            batch.append(next_id); next_id += 1
        rng.shuffle(batch)
        keep = batch[:8]
        survivors += keep
        for i in batch[8:]:
            out.append(f"f {i}")
        if len(survivors) > 120:
            for i in survivors[:40]:
                out.append(f"f {i}")
            survivors = survivors[40:]
    out += [f"f {i}" for i in survivors]
    return out


def realloc_growth(rng, buffers=60, steps=120):
    """Many buffers that grow over time, like dynamic arrays doubling."""
    out, sizes = [], {}
    for i in range(buffers):
        sizes[i] = rng.randint(16, 128)
        out.append(f"a {i} {sizes[i]}")
    for _ in range(steps * buffers // 10):
        i = rng.randrange(buffers)
        if rng.random() < 0.85:
            sizes[i] = min(int(sizes[i] * rng.uniform(1.2, 1.8)) + 1, 16384)
        else:
            sizes[i] = rng.randint(16, 128)
        out.append(f"r {i} {sizes[i]}")
    out += [f"f {i}" for i in range(buffers)]
    return out


TRACES = {
    "random-mix.trace": (random_mix, 1),
    "small-large.trace": (small_large_interleave, 2),
    "phases.trace": (phases, 3),
    "realloc-growth.trace": (realloc_growth, 4),
}


def main():
    out_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "traces")
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, (fn, seed) in TRACES.items():
        lines = fn(random.Random(seed))
        header = f"# {name}: generated by scripts/gen_traces.py (seed {seed})\n"
        (out_dir / name).write_text(header + "\n".join(lines) + "\n")
        print(f"{name}: {len(lines)} ops")


if __name__ == "__main__":
    main()
